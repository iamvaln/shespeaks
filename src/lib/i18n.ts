// French typography (no-break space before : ? ! ;) applied to every string of the French dictionary.
const typo = <T,>(v: T): T => {
  if (typeof v === 'string') return typoFr(v) as T;
  if (typeof v === 'function') return ((...a: unknown[]) => typo((v as (...x: unknown[]) => unknown)(...a))) as T;
  if (Array.isArray(v)) return v.map(typo) as T;
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, typo(x)])) as T;
  return v;
};
export const DICT: Record<Locale, Dict> = { fr: typo(fr), en };
export type { Dict };
export const t = (l: Locale): Dict => DICT[l];

export function fmtDate(iso: string | null | undefined, l: Locale, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'long', year: 'numeric' }): string {
  if (!iso) return '';
  const dateOnly = iso.length <= 10;
  const d = new Date(dateOnly ? iso + 'T12:00:00Z' : iso.replace(' ', 'T') + 'Z');
  if (Number.isNaN(d.getTime())) return iso; // a stray value (« 12/05/2026 » typed in an old browser) is shown as it is, never an error page
  // A calendar date is the same everywhere; a timestamp is stored in UTC and shown on the programme's clock (Douala, UTC+1).
  return new Intl.DateTimeFormat(l === 'fr' ? 'fr-FR' : 'en-GB', { timeZone: dateOnly ? 'UTC' : TIME_ZONE, ...opts }).format(d);
}
